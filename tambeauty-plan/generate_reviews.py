def make_nick():
    return random.choice(NICK_PREFIXES) + random.choice(NICK_SUFFIXES)


def rand_dt():
    start = datetime(2025, 6, 1, 9, 0, 0)
    end = datetime(2025, 12, 31, 23, 0, 0)
    return start + timedelta(seconds=random.randint(0, int((end - start).total_seconds())))


def fmt_dt(dt):
    ampm = "AM" if dt.hour < 12 else "PM"
    h12 = dt.hour % 12 or 12
    return f"{dt.year:04d}-{dt.month:02d}-{dt.day:02d} {h12:02d}:{dt.minute:02d}:{dt.second:02d} {ampm}"


